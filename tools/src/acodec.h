/* Minimal interface of the HiSilicon internal audio codec driver (/dev/acodec), as used by acodecctl.c.
 * Only the ioctl numbers and values this project needs; they are fixed by the driver (acodec.ko). */
#ifndef _ACODEC_H_
#define _ACODEC_H_
#include <linux/ioctl.h>
#define IOC_TYPE_ACODEC 'A'
enum { ACODEC_FS_48000 = 0x1a, ACODEC_FS_32000 = 0x1a, ACODEC_FS_16000 = 0x19, ACODEC_FS_8000 = 0x18 };
enum { ACODEC_MIXER_IN = 0x3, ACODEC_MIXER_IN_D = 0x4 };
typedef struct { unsigned int vol_ctrl; unsigned int vol_ctrl_mute; } ACODEC_VOL_CTRL;
/* ioctl numbers, in the driver's order */
enum { NR_SOFT_RESET = 0, NR_SET_INPUT_VOL, NR_SET_OUTPUT_VOL, NR_GET_INPUT_VOL, NR_GET_OUTPUT_VOL, NR_SET_I2S1_FS, NR_SET_MIXER_MIC, NR_SEL_DAC_CLK, NR_SEL_ANA_MCLK,
       NR_SET_GAIN_MICL, NR_SET_GAIN_MICR, NR_SET_DACL_VOL, NR_SET_DACR_VOL, NR_SET_ADCL_VOL, NR_SET_ADCR_VOL, NR_SET_MICL_MUTE, NR_SET_MICR_MUTE, NR_SET_DACL_MUTE, NR_SET_DACR_MUTE,
       NR_GET_GAIN_MICL, NR_GET_GAIN_MICR, NR_GET_DACL_VOL, NR_GET_DACR_VOL, NR_GET_ADCL_VOL, NR_GET_ADCR_VOL, NR_SET_PD_DACL, NR_SET_PD_DACR, NR_SET_PD_ADCL, NR_SET_PD_ADCR };
#define ACODEC_SET_I2S1_FS     _IOWR(IOC_TYPE_ACODEC, NR_SET_I2S1_FS, unsigned int)
#define ACODEC_SET_MIXER_MIC   _IOWR(IOC_TYPE_ACODEC, NR_SET_MIXER_MIC, unsigned int)
#define ACODEC_SET_GAIN_MICL   _IOWR(IOC_TYPE_ACODEC, NR_SET_GAIN_MICL, unsigned int)
#define ACODEC_SET_GAIN_MICR   _IOWR(IOC_TYPE_ACODEC, NR_SET_GAIN_MICR, unsigned int)
#define ACODEC_SET_DACL_VOL    _IOWR(IOC_TYPE_ACODEC, NR_SET_DACL_VOL, ACODEC_VOL_CTRL)
#define ACODEC_SET_DACR_VOL    _IOWR(IOC_TYPE_ACODEC, NR_SET_DACR_VOL, ACODEC_VOL_CTRL)
#define ACODEC_SET_ADCL_VOL    _IOWR(IOC_TYPE_ACODEC, NR_SET_ADCL_VOL, ACODEC_VOL_CTRL)
#define ACODEC_SET_ADCR_VOL    _IOWR(IOC_TYPE_ACODEC, NR_SET_ADCR_VOL, ACODEC_VOL_CTRL)
#define ACODEC_SET_MICL_MUTE   _IOWR(IOC_TYPE_ACODEC, NR_SET_MICL_MUTE, unsigned int)
#define ACODEC_SET_MICR_MUTE   _IOWR(IOC_TYPE_ACODEC, NR_SET_MICR_MUTE, unsigned int)
#define ACODEC_SET_DACL_MUTE   _IOWR(IOC_TYPE_ACODEC, NR_SET_DACL_MUTE, unsigned int)
#define ACODEC_SET_DACR_MUTE   _IOWR(IOC_TYPE_ACODEC, NR_SET_DACR_MUTE, unsigned int)
#define ACODEC_GET_GAIN_MICL   _IOWR(IOC_TYPE_ACODEC, NR_GET_GAIN_MICL, unsigned int)
#define ACODEC_GET_GAIN_MICR   _IOWR(IOC_TYPE_ACODEC, NR_GET_GAIN_MICR, unsigned int)
#define ACODEC_GET_DACL_VOL    _IOWR(IOC_TYPE_ACODEC, NR_GET_DACL_VOL, ACODEC_VOL_CTRL)
#define ACODEC_GET_DACR_VOL    _IOWR(IOC_TYPE_ACODEC, NR_GET_DACR_VOL, ACODEC_VOL_CTRL)
#define ACODEC_GET_ADCL_VOL    _IOWR(IOC_TYPE_ACODEC, NR_GET_ADCL_VOL, ACODEC_VOL_CTRL)
#define ACODEC_GET_ADCR_VOL    _IOWR(IOC_TYPE_ACODEC, NR_GET_ADCR_VOL, ACODEC_VOL_CTRL)
#define ACODEC_SET_PD_DACL     _IOWR(IOC_TYPE_ACODEC, NR_SET_PD_DACL, unsigned int)
#define ACODEC_SET_PD_DACR     _IOWR(IOC_TYPE_ACODEC, NR_SET_PD_DACR, unsigned int)
#define ACODEC_SET_PD_ADCL     _IOWR(IOC_TYPE_ACODEC, NR_SET_PD_ADCL, unsigned int)
#define ACODEC_SET_PD_ADCR     _IOWR(IOC_TYPE_ACODEC, NR_SET_PD_ADCR, unsigned int)
#endif
